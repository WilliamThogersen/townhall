import argparse
import json
import os
import subprocess
import sys

from PIL import Image, ImageChops

HERE = os.path.dirname(os.path.abspath(__file__))
NOT_BUILT_EXIT = 3
TOLERANCE = 16
HALF = 2
THEMES = ("dark", "light")


def scenes_wanted(wanted):
    with open(os.path.join(HERE, "scenes.json")) as f:
        scenes = json.load(f)
    names = []
    for scene in scenes:
        for theme in THEMES:
            name = scene["name"] if theme == "dark" else f"{scene['name']}-light"
            if not wanted or name in wanted:
                names.append((name, theme, scene))
    unknown = set(wanted) - {n for n, _, _ in names}
    if unknown:
        sys.exit(f"parity: unknown scene {', '.join(sorted(unknown))}")
    return names


def resolve_route(route, demo_dir):
    if "@" not in route:
        return route
    prefix, key = route.split("@", 1)
    with open(os.path.join(demo_dir, "demo.json")) as f:
        for conversation in json.load(f)["conversations"]:
            if conversation["key"] == key:
                return prefix + conversation["id"]
    sys.exit(f"parity: demo.json has no conversation {key}")


def capture_native(args, name, theme, scene, out):
    if scene["native"] is None:
        return "not built"
    shot = os.path.join(out, f"{name}.native.png")
    cmd = [
        sys.executable, "-I", os.path.join(HERE, "capture_native.py"),
        "--bin", args.bin, "--url", args.url, "--home", args.native_home,
        "--size", scene["size"], "--theme", theme,
        "--route", resolve_route(scene["native"], args.demo_dir), "--out", shot,
    ]
    root = os.path.abspath(os.path.join(HERE, "..", ".."))
    cmd += [f"--extra={arg.replace('{root}', root)}" for arg in scene.get("nativeArgs", [])]
    code = subprocess.run(cmd).returncode
    if code == NOT_BUILT_EXIT:
        return "not built"
    if code != 0:
        return f"capture failed ({code})"
    return "ok"


def mismatch(web, native):
    if web.size != native.size:
        return None
    diff = ImageChops.difference(web, native).convert("L")
    changed = sum(1 for px in diff.getdata() if px > TOLERANCE)
    return 100.0 * changed / (web.width * web.height), diff


def side_by_side(web, native, diff, path):
    mask = diff.point(lambda v: 255 if v > TOLERANCE else 0)
    red = Image.new("RGB", web.size, (255, 40, 40))
    marked = Image.composite(red, web.point(lambda v: v // 3), mask)
    panels = [web, native, marked]
    small = [p.resize((p.width // HALF, p.height // HALF), Image.LANCZOS) for p in panels]
    sheet = Image.new("RGB", (sum(p.width for p in small), small[0].height))
    x = 0
    for p in small:
        sheet.paste(p, (x, 0))
        x += p.width
    sheet.save(path, optimize=True)


def compare(name, out):
    web_path = os.path.join(out, f"{name}.web.png")
    native_path = os.path.join(out, f"{name}.native.png")
    if not os.path.exists(web_path):
        return "no web shot", None
    if not os.path.exists(native_path):
        return "native not built", None
    web = Image.open(web_path).convert("RGB")
    native = Image.open(native_path).convert("RGB")
    result = mismatch(web, native)
    if result is None:
        return f"size differs: web {web.size}, native {native.size}", None
    percent, diff = result
    side_by_side(web, native, diff, os.path.join(out, f"{name}.diff.png"))
    return "compared", percent


def write_report(rows, out):
    lines = [
        "# GPUI parity report",
        "",
        "Generated by `scripts/parity.sh`. Mismatch is the share of pixels whose channels differ by more than "
        f"{TOLERANCE}/255 between `<scene>.web.png` and `<scene>.native.png` (both 1x). 0% is 1:1.",
        "",
        "| scene | web | native | mismatch | diff |",
        "|-------|-----|--------|----------|------|",
    ]
    for name, web, native, state, percent in rows:
        pct = f"{percent:.1f}%" if percent is not None else state
        diff = f"[{name}.diff.png]({name}.diff.png)" if percent is not None else ""
        lines.append(f"| {name} | {web} | {native} | {pct} | {diff} |")
    with open(os.path.join(out, "report.md"), "w") as f:
        f.write("\n".join(lines) + "\n")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--bin", required=True)
    p.add_argument("--url", required=True)
    p.add_argument("--demo-dir", required=True)
    p.add_argument("--native-home", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("scene", nargs="*")
    args = p.parse_args()
    os.makedirs(args.out, exist_ok=True)
    rows = []
    for name, theme, scene in scenes_wanted(args.scene):
        for stale in (f"{name}.native.png", f"{name}.diff.png"):
            if os.path.exists(os.path.join(args.out, stale)):
                os.remove(os.path.join(args.out, stale))
        native = capture_native(args, name, theme, scene, args.out)
        state, percent = compare(name, args.out)
        web = "ok" if os.path.exists(os.path.join(args.out, f"{name}.web.png")) else "none"
        rows.append((name, web, native, state, percent))
        print(f"parity: {name}: web {web}, native {native}, {state}" + (f", mismatch {percent:.1f}%" if percent is not None else ""))
    write_report(rows, args.out)


if __name__ == "__main__":
    main()
